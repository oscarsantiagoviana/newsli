void Shutdown()
{
    static long done = 0;
    if (InterlockedCompareExchange(&done, 1, 0) != 0)
        return;
    InterlockedExchange(&g_shutdown, 1);
    if (g_poke != nullptr)
        SetEvent(g_poke);
    if (g_thread != nullptr)
    {
        // the thread exits without draining; the synchronous drain below
        // owns the final teardown
        WaitForSingleObject(g_thread, 1500);
        CloseHandle(g_thread);
        g_thread = nullptr;
    }
    std::lock_guard<std::mutex> lk(g_s.cs);
    if (g_st.load() != (int) St::Idle)
        DoDrain(Reason::Shutdown, 1500);
    CtlStop();
    Log("session: engine stopped");
}

