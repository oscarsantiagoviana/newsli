// offload_session.cpp — the host-side offload session (F3).
//
// Port of the POC's offload_host.cpp (2755 lines) restructured around the
// session FSM from docs/fsm-design.md. The POC had FOUR ad-hoc hot re-arm
// paths (gpuIndex, workScale, DRS, late guides) each doing partial teardown
// with its own flags; R70d proved that resetting resources possibly still
// referenced by in-flight command lists = device lost. Here there is ONE
// drain path and one creator (ARMING), both on the session thread.
//
// Frame flow (post-SR, R79 Present-gate composition):
//   evaluate(game thread) --seal--> color/depth/MV into shared bufs
//     -> produce (GPU-ordered behind the game's list, from the submit hook)
//     -> engine (GPU 2) computes a display-domain DELTA into the out buf
//     -> Present(N) (game thread, dxgi proxy): the gate waits for the
//        engine's delivery of frame N (event/fence, unbounded while the
//        engine lives), copies the delta onto the GPU and runs the NAMED
//        COMPOSE STAGE — a fullscreen-triangle draw over the swapchain
//        backbuffer on our own direct queue (multiply: the delta is a
//        GAIN, R81) — then the real Present. Frame N on screen = game
//        frame N * gain N, always.
// The game's inputs are NEVER substituted: native DLSS always sees the
// game's own color/guides, so a session death degrades to plain native SR.

