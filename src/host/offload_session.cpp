    t.nrWorkScale = 1.0f;  // 1.0 = transport exact
    t.nrBoost = 1.0f;      // 1.0 = fork exact
    t.nrTint = 0;
    t.nrTestSplit = 0;     // half-frame A/B off by default
    // (R95: nrPreSr/nrColorBack REMOVED — pre-SR placement is dead. POST-SR
    //  is the only line: the model reads the game's SR output and the
    //  Present-gate composes it same-frame. A cross-GPU round trip can
    //  never land inside the game's evaluate list (the R85w/R93 wall), so
    //  pre-SR with offload could only ever ship a stale verdict — the
    //  LEY 1 violation. The ctl id 30 is a documented hole.)
    t.nrDetail = 1.0f;     // R82k: the model's luminance verdict rides exact
    t.nrColour = 0.25f;    // R82k: the forks ship ~0; 0.25 = our R82j default
    t.nrAutoSkin = 1;      // R82k: what we always sent (UseAutoMask=1)
    t.nrGainBound = 2.0f;  // R84: per-pixel bound, fork MaxRatio default
    t.nrFlowReset = 6.0f;     // R84: history auto-reset, in-game calibrated
                              // (pan at 8 fps = 10-12%/frame; 15 let half
                              // the pans through)
    t.nrGateWaitMs = 0;       // R88: UNBOUNDED gate wait (max NR fidelity —
                              // the presented frame always carries its own
                              // delta; bounded wait is opt-in via panel/ini)
    t.nrPerfQuality = 2.0f;   // R90 (#1): vendor PerfQualityValue 0..4;
                              // 2 = MaxQuality, what always ran
    t.nrRatioPin = 0.0f;      // golpe 1b: 0 = valve OPEN (model computes
                              // its own work ratio from PQV); >0 = pinned
                              // (1.0 = classic full-res rollback)
    t.nrDepthMode = 0u;       // golpe 2: 0 = REAL depth (clone seal;
                              // coherent 1.0 proxy fallback when the frame
                              // carries none); 1 = always flat proxy
    // R82g.4: nrModelH removed from the ABI — the answer fills the whole
