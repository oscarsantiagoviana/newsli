// R82f: the depth guide is a FLAT ZERO plane (RDR2's log depth poisons
// the runtime's reprojection — measured, see Session comment). Each ring
// slot is filled by a plain buffer copy from a persist-mapped upload of
// zeros; the game's depth resource is never touched (no DSV barriers, no
// clone). This replaces the R69t clone path wholesale.
void RecordDepthCapture(const EvalArgs& a, ID3D12GraphicsCommandList* list)
{
    // golpe 2: REAL depth when the frame carries one (nrDepthMode 0) — the
    // R69t clone path, restored verbatim after the feeder refuted the R82f
    // poison verdict (worklog 36). The fallback (no depth / mode 1) ships
    // the flat 1.0 plane: COHERENT with depthInverted=1 (near = 1), fixing
    // the zeros=far inconsistency the comparativa found.
    Session& s = g_s;
    SharedBuf& sb = s.guideD[s.frame % 3];

    // golpe 2 (R1 fix): the ARM is one-shot and menus carry no depth —
    // create the clone LAZILY at the first seal that actually sees one
    // (CreateCommittedResource is thread-safe; the desc comes from the
    // live resource, fresher than any arm snapshot).
    if (s.tuning.nrDepthMode == 0u && a.srcDepth != nullptr &&
        s.depthClone == nullptr && !s.depthCloneTried &&
        s.gameDev != nullptr)
    {
        s.depthCloneTried = true;   // one attempt per session (drain resets)
        if ((a.srcDepth->GetDesc().Flags &
             D3D12_RESOURCE_FLAG_ALLOW_DEPTH_STENCIL) == 0)
        {
            Log("session: depth resource is not DSV (flags %u) - real "
                "depth unavailable this session",
                (unsigned) a.srcDepth->GetDesc().Flags);
        }
        else
        {
            D3D12_HEAP_PROPERTIES hp {};
            hp.Type = D3D12_HEAP_TYPE_DEFAULT;
            D3D12_RESOURCE_DESC d = a.srcDepth->GetDesc();
            if (FAILED(s.gameDev->CreateCommittedResource(
                    &hp, D3D12_HEAP_FLAG_NONE, &d,
                    D3D12_RESOURCE_STATE_DEPTH_WRITE, nullptr,
                    IID_PPV_ARGS(&s.depthClone))))
                Log("session: depth clone failed - staying on proxy");
            else
                Log("session: depth clone ok (%ux%u fmt %u) - REAL depth "
                    "guide live",
                    (unsigned) d.Width, (unsigned) d.Height,
                    (unsigned) d.Format);
        }
    }

    if (s.tuning.nrDepthMode == 0u && a.srcDepth != nullptr &&
        s.depthClone != nullptr && sb.buf != nullptr &&
        (a.srcDepth->GetDesc().Flags & D3D12_RESOURCE_FLAG_ALLOW_DEPTH_STENCIL))
    {
        D3D12_RESOURCE_BARRIER bd {};
        bd.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
        bd.Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
        bd.Transition.pResource = a.srcDepth;
        bd.Transition.StateBefore = D3D12_RESOURCE_STATE_DEPTH_WRITE;
        bd.Transition.StateAfter = D3D12_RESOURCE_STATE_COPY_SOURCE;
        list->ResourceBarrier(1, &bd);
        D3D12_RESOURCE_BARRIER bc {};
        bc.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
        bc.Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
        bc.Transition.pResource = s.depthClone.Get();
        bc.Transition.StateBefore = D3D12_RESOURCE_STATE_DEPTH_WRITE;
        bc.Transition.StateAfter = D3D12_RESOURCE_STATE_COPY_DEST;
        list->ResourceBarrier(1, &bc);
        list->CopyResource(s.depthClone.Get(), a.srcDepth);
        bd.Transition.StateBefore = D3D12_RESOURCE_STATE_COPY_SOURCE;
        bd.Transition.StateAfter = D3D12_RESOURCE_STATE_DEPTH_WRITE;
        list->ResourceBarrier(1, &bd);
        bc.Transition.StateBefore = D3D12_RESOURCE_STATE_COPY_DEST;
        bc.Transition.StateAfter = D3D12_RESOURCE_STATE_COPY_SOURCE;
        list->ResourceBarrier(1, &bc);
        {
            D3D12_TEXTURE_COPY_LOCATION srcL { s.depthClone.Get(),
                D3D12_TEXTURE_COPY_TYPE_SUBRESOURCE_INDEX };
            srcL.SubresourceIndex = 0;  // plane 0 = depth
            D3D12_TEXTURE_COPY_LOCATION dstL { sb.buf.Get(),
                D3D12_TEXTURE_COPY_TYPE_PLACED_FOOTPRINT };
            dstL.PlacedFootprint.Footprint.Format = DXGI_FORMAT_R32_FLOAT;
            dstL.PlacedFootprint.Footprint.Width = s.guideW;
            dstL.PlacedFootprint.Footprint.Height = s.guideH;
            dstL.PlacedFootprint.Footprint.Depth = 1;
            dstL.PlacedFootprint.Footprint.RowPitch = s.guideDepthPitch;
            D3D12_BOX box {};
            box.left = a.depthBaseX; box.top = a.depthBaseY; box.front = 0;
            box.right = a.depthBaseX + s.guideW;
            box.bottom = a.depthBaseY + s.guideH;
            box.back = 1;
            list->CopyTextureRegion(&dstL, 0, 0, 0, &srcL, &box);
        }
        bc.Transition.StateBefore = D3D12_RESOURCE_STATE_COPY_SOURCE;
        bc.Transition.StateAfter = D3D12_RESOURCE_STATE_DEPTH_WRITE;
        list->ResourceBarrier(1, &bc);
        return;
    }

    // fallback: the pre-built flat plane (1.0 = near under inverted
    // labelling — COHERENT with the engine's depthInverted=1)
    ID3D12Resource* up = s.depthZeroUp[s.frame % 3].Get();
    if (up == nullptr || sb.buf == nullptr)
        return;
    const UINT64 bytes = (UINT64) s.guideDepthPitch * s.guideH;
    list->CopyBufferRegion(sb.buf.Get(), 0, up, 0, bytes);
}

// Seal one frame: color into the GAME'S list (executes at the exact point
// native DLSS reads it — call-time sealing read a stale cleared MV in v1),
// depth through the clone in the same list, and guides + delta staging into
// the private seal list submitted behind the frame.
bool RecordSealFrame(const EvalArgs& a, ID3D12GraphicsCommandList* list)
{
    // ---- colour: R95 — POST-SR only, sealed AFTER the native evaluate
    // by SealColorPost (the SR output is the model's input). Nothing is
    // recorded here for colour.

// ---- depth: clone path, same list ---------------------------------
    RecordDepthCapture(a, list);

    // ---- guides + delta staging: the private seal list ----------------
    // R82h: guides are RENDER-sized even when the colour rides POST-SR at
    // display res — compare against the frame's render dims.
    const bool guidesOk = a.srcMotion != nullptr &&
                          g_s.guideW == a.inW && g_s.guideH == a.inH;
    if (a.srcMotion != nullptr && g_s.guideW == 0)
    {
        // armed without guides (menu/load screen) and they appeared: the
        // guide buffers never existed with these dims — re-arm.
        static bool lateLogged = false;
        if (!lateLogged)
        {
            lateLogged = true;
            Log("session: guides appeared late - reconfig");
        }
        EnqueueReconfig(Reason::LateGuides);
        return true;  // color/depth sealed; engine idles on stale guides
    }
    if (!guidesOk)
    {
        // R82k.6 DIMENSION GUARD: the game changed its render geometry
        // under a live session (DLSS level change, DRS) — the ringed MVs
        // are stale and a stale-MV evaluate warps the model's history
        // against the wrong motion (the "ghost ahead/behind" class).
        // Re-arm to resize every buffer; the no-MV frames until then run
        // with mvScale 0 (no warp at all: the model degrades to a pure
        // spatial denoise for those frames — far better than a false warp).
        if (a.srcMotion != nullptr)
        {
            static bool geomLogged = false;
            if (!geomLogged)
            {
                geomLogged = true;
                Log("session: render geometry moved %ux%u -> %ux%u - reconfig",
                    g_s.guideW, g_s.guideH, a.inW, a.inH);
            }
            EnqueueReconfig(Reason::Drs);
        }
        if (g_s.scalars != nullptr)
        {
            g_s.scalars->mvScaleX = 0.f;
            g_s.scalars->mvScaleY = 0.f;
        }
        return true;  // no MV this frame: color-only seal
    }

    {
        std::lock_guard<std::mutex> lk(g_s.pendingCs);
        if (g_s.sealCmd == nullptr)
        {
            if (FAILED(g_s.gameDev->CreateCommandAllocator(
                    D3D12_COMMAND_LIST_TYPE_DIRECT,
                    IID_PPV_ARGS(&g_s.sealAlloc))) ||
                FAILED(g_s.gameDev->CreateCommandList(
                    0, D3D12_COMMAND_LIST_TYPE_DIRECT, g_s.sealAlloc.Get(),
                    nullptr, IID_PPV_ARGS(&g_s.sealCmd))))
            {
                Log("session: seal command objects failed - guides off");
                g_s.sealCmd.Reset();
                g_s.sealAlloc.Reset();
                return true;
            }
            // a freshly created list is in recording state; Reset demands
            // a CLOSED one — close it empty so the cycle works from the
            // first frame
            g_s.sealCmd->Close();
        }
        const HRESULT hrR = g_s.sealCmd->Reset(g_s.sealAlloc.Get(), nullptr);
        if (FAILED(hrR))
        {
            Log("session: seal list Reset hr 0x%08X", (unsigned) hrR);
            return true;
        }

        // MV guide -> triple buffer (raw game format footprint)
        {
            SharedBuf& sb = g_s.guideM[g_s.frame % 3];
            if (sb.buf != nullptr)
            {
                const bool isDsv =
                    (a.srcMotion->GetDesc().Flags &
                     D3D12_RESOURCE_FLAG_ALLOW_DEPTH_STENCIL) != 0;
                D3D12_RESOURCE_BARRIER bs {};
                bs.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
                bs.Transition.Subresource =
                    D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
                bs.Transition.pResource = a.srcMotion;
                bs.Transition.StateBefore = isDsv
                    ? D3D12_RESOURCE_STATE_DEPTH_WRITE
                    : D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE;
                bs.Transition.StateAfter = D3D12_RESOURCE_STATE_COPY_SOURCE;
                g_s.sealCmd->ResourceBarrier(1, &bs);
                D3D12_TEXTURE_COPY_LOCATION gs { a.srcMotion,
                    D3D12_TEXTURE_COPY_TYPE_SUBRESOURCE_INDEX };
                D3D12_TEXTURE_COPY_LOCATION gd { sb.buf.Get(),
                    D3D12_TEXTURE_COPY_TYPE_PLACED_FOOTPRINT };
                gd.PlacedFootprint.Footprint.Format =
                    (DXGI_FORMAT) g_s.guideMvFmt;
                // R82h: the guide buffer is RENDER-sized (guideW/H) even
                // when the colour transport rides POST-SR at display res —
                // a display-sized footprint overran the buffer and Close
                // reported E_INVALIDARG.
                gd.PlacedFootprint.Footprint.Width = g_s.guideW;
                gd.PlacedFootprint.Footprint.Height = g_s.guideH;
                gd.PlacedFootprint.Footprint.Depth = 1;
                gd.PlacedFootprint.Footprint.RowPitch = g_s.guideMvPitch;
                D3D12_BOX gb {};
                gb.left = a.motionBaseX; gb.top = a.motionBaseY; gb.front = 0;
                gb.right = a.motionBaseX + g_s.guideW;
                gb.bottom = a.motionBaseY + g_s.guideH;
                gb.back = 1;
                // clamp the box to the MV's real extent: a base beyond the
                // source made the copy record invalid (Close E_INVALIDARG)
                const D3D12_RESOURCE_DESC md0 = a.srcMotion->GetDesc();
                if (gb.right  > md0.Width) gb.right  = (UINT) md0.Width;
                if (gb.bottom > md0.Height) gb.bottom = (UINT) md0.Height;
                g_s.sealCmd->CopyTextureRegion(&gd, 0, 0, 0, &gs, &gb);
                bs.Transition.StateBefore =
                    D3D12_RESOURCE_STATE_COPY_SOURCE;
                bs.Transition.StateAfter = isDsv
                    ? D3D12_RESOURCE_STATE_DEPTH_WRITE
                    : D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE;
                g_s.sealCmd->ResourceBarrier(1, &bs);
            }
        }

        // (R82l: the R82h DIAG close/reopen around the MV-ring copy is gone
        // WITH the ring — it existed only to identify that copy's
        // E_INVALIDARG. The seal is one command group again.)

        const HRESULT hrC = g_s.sealCmd->Close();
        if (SUCCEEDED(hrC))
            g_s.sealRecorded = true;
        else
        {
            Log("session: seal list close failed hr 0x%08X (frame %u) - "
                "rebuilding", (unsigned) hrC, g_s.frame);
            g_s.sealCmd.Reset();
            g_s.sealAlloc.Reset();
            g_s.sealRecorded = false;
        }
    }
    return true;
}

