// D3D12 format tables (POC-verbatim; see analysis/01-host-analysis.md §4.5).
// Copy footprints reject TYPELESS formats — and empirically the SINT/UINT
// members of a family too (this game's R32G32_SINT depth was rejected at
// Close while its R32_FLOAT twin passed) — so every copy declares the FLOAT
// member of the source format's family: same parent typeless, same layout,
// identical bits.
// ---------------------------------------------------------------------------

unsigned BppFor(unsigned fmt)
{
    switch (fmt)
    {
        case 1: case 2: case 3: case 4:            // R32G32B32A32 family
            return 16;
        case 5: case 6: case 7: case 8:            // R32G32B32
        case 9: case 10: case 11: case 12: case 13: case 14: case 15:
        case 16: case 17: case 18: case 19:        // R32G32 (this game's MV)
        case 20: case 21: case 22: case 23:        // R32G8X24
            return 8;
        case 56: case 57: case 58: case 59:        // R16
            return 2;
        default:
            return 4;  // R8G8B8A8, R32, R16G16, R10G10B10A2, R11G11B10, ...
    }
}

unsigned PitchFor(unsigned width, unsigned bpp)
{
    return (width * bpp + 255u) & ~255u;  // footprints require 256 B rows
}

unsigned FootprintFmt(unsigned fmt)
{
    switch (fmt)
    {
        case 1: case 3: case 4: return 2;                    // RGBA32 -> FLOAT
        case 5: case 7: case 8: return 6;                    // RGB32 -> FLOAT
        case 9: case 11: case 12: case 13: case 14: case 15:
            return 10;                                       // RGBA16 -> FLOAT
        case 16: case 18: case 19: return 17;                // R32G32 -> FLOAT
        case 20: case 22: case 23: return 21;                // R32G8X24
        case 24: case 26: return 25;                         // R10G10B10A2
        case 28: case 29: case 30: case 31: return 29;       // R8G8B8A8
        case 33: case 35: case 36: return 34;                // R16G16
        case 40: case 42: case 43: return 41;                // R32
        case 45: case 47: case 48: return 46;                // R24G8
        case 56: case 58: case 59: return 57;                // R16
        case 65: case 66: case 67: case 68: return 65;       // R8
        default: return fmt;  // FLOAT members and odd cases pass through
    }
}

// Directory of this DLL: the engine exe, the vendor runtime and the user
// config all deploy beside the proxy (same layout the POC used).
void DllDirW(wchar_t* out, size_t cch)
{
    wchar_t wd[MAX_PATH] = {};
    GetModuleFileNameW(nullptr, wd, MAX_PATH);
    // the DLL's own path, not the game exe's: resolve through our address
    wchar_t dll[MAX_PATH] = {};
    HMODULE self = nullptr;
    if (GetModuleHandleExW(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS |
                               GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,
                           (LPCWSTR) &DllDirW, &self) &&
        self != nullptr)
        GetModuleFileNameW(self, dll, MAX_PATH);
    else
        wcscpy_s(dll, MAX_PATH, wd);
    wchar_t* slash = wcsrchr(dll, L'\\');
    if (slash) *slash = 0;
    wcsncpy_s(out, cch, dll, _TRUNCATE);
}

// ---------------------------------------------------------------------------
// FSM (docs/fsm-design.md). g_st is the ONLY thing the game thread reads:
// one acquire-load, anything != Live means "not my frame" — it can never
// wait on the machine.
// ---------------------------------------------------------------------------

enum class St { Idle = 0, Arming, Live, Draining, Cooldown };

enum class Reason
{
    None,        // no request pending
    GpuIndex,    // panel switched the transport GPU      -> re-arm
    WorkScale,   // engine model dims changed              -> re-arm
    Drs,         // render geometry changed                -> re-arm
    LateGuides,  // armed without guides, they appeared    -> re-arm
    Recycle,     // engine working-set over budget         -> re-arm
    EngineDead,  // process exited / spawn failed          -> cooldown
    FencePoison, // shared done fence hit UINT64_MAX (TDR) -> cooldown
    FailStreak,  // engine kept failing 90 s               -> cooldown
    Shutdown     // game exit                              -> idle, stop
};

const char* ReasonName(Reason r)
{
    switch (r)
    {
        case Reason::GpuIndex:    return "gpuIndex";
        case Reason::WorkScale:   return "workScale";
        case Reason::Drs:         return "geometry";
        case Reason::LateGuides:  return "lateGuides";
        case Reason::Recycle:     return "recycle";
        case Reason::EngineDead:  return "engineDied";
        case Reason::FencePoison: return "fencePoison";
        case Reason::FailStreak:  return "failStreak";
        case Reason::Shutdown:    return "shutdown";
        default:                  return "none";
    }
}

std::atomic<int> g_st{ static_cast<int>(St::Idle) };

// ---------------------------------------------------------------------------
// Shared transport: cross-adapter placed buffers (the shape this machine's
// MGPU bridge validated; shared placed TEXTURES are rejected by the driver).
// ---------------------------------------------------------------------------

struct SharedBuf
{
    ComPtr<ID3D12Heap> heap;
    ComPtr<ID3D12Resource> buf;
    HANDLE nt = nullptr;

    void Reset()
    {
        if (nt != nullptr) { CloseHandle(nt); nt = nullptr; }
        buf.Reset();
        heap.Reset();
    }
};

// R90 (#11): the out transport is a 3-slot ring on ONE shared heap. The
// heap carries kOutRingSlots buffers at k*stride offsets (stride =
// RoundUp64K(frameBytes), the abi.h layout contract the engine mirrors).
// The single NT handle shares the whole heap; slots are placed views.
struct OutRing
{
    ComPtr<ID3D12Heap> heap;
    ComPtr<ID3D12Resource> buf[sli::kOutRingSlots];
    UINT64 stride = 0;
    HANDLE nt = nullptr;

    bool Make(ID3D12Device* dev, UINT64 frameBytes, const char* what);
    void Reset()
    {
        if (nt != nullptr) { CloseHandle(nt); nt = nullptr; }
        for (auto& b : buf) b.Reset();
        heap.Reset();
        stride = 0;
    }
};

bool OutRing::Make(ID3D12Device* dev, UINT64 frameBytes, const char* what)
{
    stride = (frameBytes + 65535) / 65536 * 65536;
    D3D12_HEAP_PROPERTIES hp {};
    hp.Type = D3D12_HEAP_TYPE_DEFAULT;
    hp.CreationNodeMask = 1;
    hp.VisibleNodeMask = 1;
    D3D12_HEAP_DESC hd {};
    hd.SizeInBytes = stride * sli::kOutRingSlots;
    hd.Properties = hp;
    hd.Alignment = 65536;
    hd.Flags = D3D12_HEAP_FLAG_SHARED | D3D12_HEAP_FLAG_SHARED_CROSS_ADAPTER;
    HRESULT hr = dev->CreateHeap(&hd, IID_PPV_ARGS(&heap));
    if (FAILED(hr))
    {
        Log("session: %s: ring CreateHeap failed 0x%08X", what, (unsigned) hr);
        return false;
    }
    D3D12_RESOURCE_DESC d {};
    d.Dimension = D3D12_RESOURCE_DIMENSION_BUFFER;
    d.Width = frameBytes;
    d.Height = 1;
    d.DepthOrArraySize = 1;
    d.MipLevels = 1;
    d.Format = DXGI_FORMAT_UNKNOWN;
    d.SampleDesc.Count = 1;
    d.Layout = D3D12_TEXTURE_LAYOUT_ROW_MAJOR;
    d.Flags = D3D12_RESOURCE_FLAG_ALLOW_CROSS_ADAPTER;
    for (uint64_t k = 0; k < sli::kOutRingSlots; ++k)
    {
        hr = dev->CreatePlacedResource(heap.Get(), k * stride, &d,
                                       D3D12_RESOURCE_STATE_COMMON, nullptr,
                                       IID_PPV_ARGS(&buf[k]));
        if (FAILED(hr))
        {
            Log("session: %s: ring slot %llu CreatePlacedResource failed "
                "0x%08X", what, (unsigned long long) k, (unsigned) hr);
            return false;
        }
    }
    hr = dev->CreateSharedHandle(heap.Get(), nullptr, GENERIC_ALL, nullptr,
                                 &nt);
    if (FAILED(hr))
    {
        Log("session: %s: ring CreateSharedHandle failed 0x%08X", what,
            (unsigned) hr);
        return false;
    }
    return true;
}

bool MakeSharedBuf(ID3D12Device* dev, UINT64 bytes, SharedBuf& s, const char* what)
{
    D3D12_HEAP_PROPERTIES hp {};
    // HEAP_TYPE_DEFAULT (VRAM of the game's GPU): the copy engines reach it
    // from both adapters and it keeps ~44 MB of frame data out of system
    // memory. (The POC's R69k comment claimed a CUSTOM/system heap; the code
    // it shipped always used DEFAULT — audited, kept as built.)
    hp.Type = D3D12_HEAP_TYPE_DEFAULT;
    hp.CreationNodeMask = 1;
    hp.VisibleNodeMask = 1;
    D3D12_HEAP_DESC hd {};
    hd.SizeInBytes = (bytes + 65535) / 65536 * 65536;  // 64 K alignment
    hd.Properties = hp;
    hd.Alignment = 65536;
    hd.Flags = D3D12_HEAP_FLAG_SHARED | D3D12_HEAP_FLAG_SHARED_CROSS_ADAPTER;
    HRESULT hr = dev->CreateHeap(&hd, IID_PPV_ARGS(&s.heap));
    if (FAILED(hr))
    {
        Log("session: %s: CreateHeap failed 0x%08X", what, (unsigned) hr);
        return false;
    }
    D3D12_RESOURCE_DESC d {};
    d.Dimension = D3D12_RESOURCE_DIMENSION_BUFFER;
    d.Width = bytes;
    d.Height = 1;
    d.DepthOrArraySize = 1;
    d.MipLevels = 1;
    d.Format = DXGI_FORMAT_UNKNOWN;
    d.SampleDesc.Count = 1;
    d.Layout = D3D12_TEXTURE_LAYOUT_ROW_MAJOR;
    d.Flags = D3D12_RESOURCE_FLAG_ALLOW_CROSS_ADAPTER;
    hr = dev->CreatePlacedResource(s.heap.Get(), 0, &d,
                                   D3D12_RESOURCE_STATE_COMMON, nullptr,
                                   IID_PPV_ARGS(&s.buf));
    if (FAILED(hr))
    {
        Log("session: %s: CreatePlacedResource failed 0x%08X", what, (unsigned) hr);
        return false;
    }
    hr = dev->CreateSharedHandle(s.heap.Get(), nullptr, GENERIC_ALL, nullptr, &s.nt);
    if (FAILED(hr))
    {
        Log("session: %s: CreateSharedHandle failed 0x%08X", what, (unsigned) hr);
        return false;
    }
    return true;
}

bool MakeSharedFence(ID3D12Device* dev, ComPtr<ID3D12Fence>& f, HANDLE* nt)
{
    if (FAILED(dev->CreateFence(0, D3D12_FENCE_FLAG_SHARED |
                                     D3D12_FENCE_FLAG_SHARED_CROSS_ADAPTER,
                                IID_PPV_ARGS(&f))))
    {
        // R89d: the arm-fail wrapper only names the group ("shared
        // transport") — the primitive that actually failed logs itself.
        Log("session: shared fence create failed (GetDeviceRemovedReason "
            "see engine/host logs)");
        return false;
    }
    if (!SUCCEEDED(dev->CreateSharedHandle(f.Get(), nullptr, GENERIC_ALL,
                                           nullptr, nt)))
    {
        Log("session: shared fence handle failed %u",
            (unsigned) GetLastError());
        return false;
    }
    return true;
}

// First NVIDIA adapter that is not the game's (or the wantIndex-th one).
// The game adapter is skipped explicitly: an offload onto the same GPU
// would only add cross-process latency.
bool PickSecondAdapterLuid(ID3D12Device* gameDev, unsigned long long& lo,
                           unsigned long long& hi,
                           unsigned long long& gameLo, unsigned long long& gameHi,
                           int wantIndex)
{
    const LUID gameLuid = gameDev->GetAdapterLuid();
    gameLo = (unsigned long long) gameLuid.LowPart;
    gameHi = (unsigned long long) gameLuid.HighPart;
    ComPtr<IDXGIFactory4> factory;
    if (FAILED(CreateDXGIFactory1(IID_PPV_ARGS(&factory))))
        return false;
    int nvidiaSeen = -1;
    for (UINT i = 0;; ++i)
    {
        ComPtr<IDXGIAdapter1> ad;
        if (factory->EnumAdapters1(i, ad.ReleaseAndGetAddressOf()) != S_OK)
            break;
        DXGI_ADAPTER_DESC1 d {};
        if (FAILED(ad->GetDesc1(&d)) || d.VendorId != 0x10DE)
            continue;
        if (d.AdapterLuid.LowPart == gameLuid.LowPart &&
            d.AdapterLuid.HighPart == gameLuid.HighPart)
            continue;
        ++nvidiaSeen;
        if (wantIndex < 0 || nvidiaSeen == wantIndex)
        {
            lo = d.AdapterLuid.LowPart;
            hi = d.AdapterLuid.HighPart;
            char name[256] = {};
            WideCharToMultiByte(CP_UTF8, 0, d.Description, -1, name,
                                sizeof(name), nullptr, nullptr);
            Log("session: offload adapter%s: %s",
                wantIndex < 0 ? "" : " (selected)", name);
            return true;
        }
    }
    return false;
}

// ---------------------------------------------------------------------------
// Compose stage: GPU-0 objects for the NAMED COMPOSE STAGE at Present —
// a fullscreen-triangle draw of the engine's gain over the swapchain
// backbuffer. Backend-agnostic by design (R79b): PresentGate
// only calls ComposeStageDraw(); a future FG/SR backend plugs in the same
// way. All of it dies with the session (delivery state never survives a
// drain — the R70i stale-freeze class).
// ---------------------------------------------------------------------------

struct ComposeGpu
{
    // PSO objects (ARMING, session thread)
    ComPtr<ID3D12RootSignature> rs;
    // graphics PSOs keyed by backbuffer format (RTVFormats is immutable
    // in a PSO; a swapchain recreate can change the format) — lazy, small.
    // R81: [0,4) = multiply (quality), [4] = additive (debug views).
    static constexpr int kMaxPso = 5;
    ComPtr<ID3D12PipelineState> pso[kMaxPso];
    DXGI_FORMAT psoFmt[kMaxPso] = {};
    ComPtr<ID3D12DescriptorHeap> heap;   // 1: t0 (delta SRV), shader-visible
    ComPtr<ID3D12DescriptorHeap> rtvHeap; // 4: backbuffer RTVs, non-shader-visible
    ComPtr<ID3D12Resource> texDelta;     // render-res delta (engine output)
    UINT rtvInc = 0;
    ComPtr<ID3D12Device> gameDev;
    bool ok = false;
    // our own direct queue + draw list (never the game's — R79). R90 (#7):
    // THREE allocator/list pairs + a per-slot fence value — the Present
    // path no longer blocks on a flush just to recycle ONE allocator; it
    // waits only when it is genuinely 3 slots behind (never in regime).
    // A wedged GPU is the watchdog's business (10 s), and the flip order
    // is the queue's FIFO, not this flush.
    ComPtr<ID3D12CommandQueue> queue;
    static constexpr int kComposeRing = 3;
    ComPtr<ID3D12CommandAllocator> alloc[kComposeRing];
    ComPtr<ID3D12GraphicsCommandList> cmd[kComposeRing];
    ComPtr<ID3D12Fence> fence;
    HANDLE fenceEvt = nullptr;
    uint64_t fenceVal[kComposeRing] = {};   // value signalled per slot
    int ringNext = 0;
    // verification-only structural view moved to the ENGINE (R82d): the
    // decode CS itself maintains the EMA of the gain in a persistent UAV —
    // no host-side accumulator, no merge pass, nothing to lazy-init here
    // backbuffer RTV cache: up to 4 slots keyed by resource pointer
    // (GetBuffer returns a different resource after a resize)
    static constexpr int kMaxRtv = 4;
    ID3D12Resource* bbRes[kMaxRtv] = {};
    ComPtr<ID3D12Resource> bbHold[kMaxRtv];
    bool rtvValid[kMaxRtv] = {};
};

// ---------------------------------------------------------------------------
// The session: everything the engine process and the compose path own.
// Members are touched by exactly one of: the session thread (creation and
// destruction, under cs), the game thread (seal/compose/deliver, only while
// g_st == Live and counted in g_frameBusy), or the submit thread (the
// pending triple + seal list, under pendingCs).
// ---------------------------------------------------------------------------

struct Session
{
    std::mutex cs;                    // session thread transitions ONLY
    bool enabled = false;             // Configure(>=0) decided at NGX init
    bool failedPermanent = false;     // no second NVIDIA adapter: stay native

    // arm snapshot (written by the game thread, consumed by the session
    // thread — POD + a device reference; resources are re-read per frame)
    std::mutex armCs;
    struct Arm
    {
        bool valid = false;
        ComPtr<ID3D12Device> dev;
        unsigned inW = 0, inH = 0, outW = 0, outH = 0;
        DXGI_FORMAT colorFmt = DXGI_FORMAT_UNKNOWN;
        DXGI_FORMAT outFmt = DXGI_FORMAT_UNKNOWN;
        DXGI_FORMAT mvFmt = DXGI_FORMAT_UNKNOWN;
        D3D12_RESOURCE_DESC depthDesc {};
        bool hasDepth = false, hasMv = false;
        unsigned srFlags = 0;
    } arm;
    // transport (ARMING creates, DRAINING releases)
    ComPtr<ID3D12Device> gameDev;
    unsigned inW = 0, inH = 0;
    DXGI_FORMAT colorFmt = DXGI_FORMAT_UNKNOWN;
    unsigned srFlags = 0;
    unsigned long long luidLo = 0, luidHi = 0;
    unsigned long long gameLuidLo = 0, gameLuidHi = 0;
    SharedBuf inColor;
    OutRing out;                    // R90 (#11): 3-slot delivery ring
    ComPtr<ID3D12Fence> produceFence, doneFence;
    HANDLE ntProduce = nullptr, ntDone = nullptr;
    HANDLE map = nullptr;
    FrameScalars* scalars = nullptr;
    wchar_t mapName[64] = {};

    // guides (real game MV, FLAT PROXY depth; triple-buffered; the engine
    // evaluates frame N with frame N's guides — produce N is signaled only
    // after the seal that writes guide[N%3] has executed, so color and
    // guides are a coherent set, same as the game hands to native NGX)
    SharedBuf guideD[3], guideM[3];
    unsigned guideDepthFmt = 0, guideMvFmt = 0;
    unsigned guideDepthPitch = 0, guideMvPitch = 0;
    unsigned guideW = 0, guideH = 0;   // RENDER res always (R82h): the MV/
                                       // depth the game produces are render-
                                       // sized even when the colour rides
                                       // POST-SR at display res; the engine
                                       // scales guides to its work size.
    // R82f: the depth guide ships as a FLAT ZERO plane (upload ring) —
    // RDR2's log depth (whole scene in 0..0.08) poisons the runtime's
    // reprojection into a mono-channel answer in ANY labelling (measured
    // raw / inverted / clamped / rescaled); the reference hosts agree
    // (obs ships no depth, the webcam demo authors a proxy). The MVs stay
    // REAL: proven harmless and they carry the motion signal.
    ComPtr<ID3D12Resource> depthZeroUp[3];
    void* depthZeroMap[3] = {};
    // golpe 2: the R69t clone — an identical-desc twin of the game's depth
    // (CopyTextureRegion forbids a DSV-flagged source). The seal copies the
    // game's depth into it inside the game's own list, then plane 0 feeds
    // guideD as R32_FLOAT. Null when the arming frame carried no depth.
    ComPtr<ID3D12Resource> depthClone;
    // (R95 audit: depthRealFrames removed — incremented but never read;
    //  its promised "rate log" consumer never shipped.)
    bool depthCloneTried = false;

    // (The MV ring is GONE — R82l. Its own comment said it served "forensics
    // and future FG work" after the R78 reprojection died: 8 render-res
    // textures (~75 MB of GAME VRAM), a per-frame copy with 4 resource
    // barriers on the seal's hot path, and a DIAG-only reader. No-legacy
    // rule: deleted. The guides the engine really consumes are sealed
    // separately (guideD/guideM).)

    // ---- Present gate (R79) ----
    // delivery wait objects: done-fence event + engine process handle
    HANDLE doneEvt = nullptr;
    // generation the gate last saw: a re-arm invalidates an in-flight wait
    uint64_t generation = 0;
    // last HOST frame the gate composed (one compose per frame max)
    uint64_t gateComposedFrame = 0;
    // last done-fence value the gate observed (delivery bookkeeping)
    uint64_t gateLastDone = 0;
    // permanent degrade latch: set once per session by any PresentGate
    // fallback; cleared only on re-arm (ComposeHalt + native presents)
    bool composeDegraded = false;

    // the seal list: guides + delta staging, submitted BEHIND the game's
    // frame list on the same queue. NEVER record barriers on the game's
    // textures inside its own list beyond the two net-zero seals — the
    // in-list corruption class cost five RDR2 sessions (R69q).
    ComPtr<ID3D12CommandAllocator> sealAlloc;
    ComPtr<ID3D12GraphicsCommandList> sealCmd;
    bool sealRecorded = false;

    // engine process
    PROCESS_INFORMATION pi {};
    bool engineRunning = false;

    std::atomic<DWORD> enginePid{ 0 };

    // per-frame delivery state (dies with the path)
    uint64_t frame = 0;
    uint64_t lastDeliveredDone = 0;
    unsigned consecutiveFailures = 0;
    ULONGLONG firstFailureTick = 0;

    // pending triple (submit thread; own mutex — the submit hook must
    // never wait on the session mutex, R69i)
    std::mutex pendingCs;
    bool pendingValid = false;
    uint64_t pendingFrame = 0;
    ID3D12GraphicsCommandList* pendingList = nullptr;

    ComposeGpu compose;

    // the game's queue last seen at an evaluate — DRAINING flushes it (a
    // private fence, GPU-ordered) before releasing anything the game's
    // recorded lists reference (R70d)
    ComPtr<ID3D12CommandQueue> gameQueueForFlush;

    // live tuning (host-authoritative copy, relayed into the mapping)
    Tuning tuning {};
    bool tuningInit = false;
    bool panelOwned[CTL_FIELD_COUNT] = {};   // mirror source flags; sized by
                                             // CTL_FIELD_COUNT (R89a: it
                                             // stayed [32] when the ids
                                             // reached 39 — fields 33-39
                                             // wrote past the end, the
                                             // R82k.7 trample class again)
};

