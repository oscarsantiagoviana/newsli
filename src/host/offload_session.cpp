// R82h SealColorPost — the colour seal. The proxy calls this right
// after the native evaluate has been recorded into the game's list, so
// this copy GPU-orders AFTER the SuperResolution passes: what lands in
// the transport is the game's SR OUTPUT — the de-jittered, display-
// referred frame the NR model was trained on. This is the ONLY colour
// seal (the R95 extirpation removed the pre-SR placement for good).
//
// The output's arrival state is the one the NGX core restores (it leaves
// resources as it found them); RDR2 hands the evaluate a UAV-family target,
// which is the assumption every OptiScaler-family host makes for its
// after-upscale pass (Aurora: outputArrival = UNORDERED_ACCESS, with an ini
// escape hatch we do not need while the A/B view proves the capture).
// ---------------------------------------------------------------------------
// GOLPE 5 (pre-SR real, deferred): REMOVED in R95 — see the Tuning
// defaults note. The functions below (Ensure/Stage/Compose/Swap) died
// with the mode; what remains of the colour path is SealColorPost only.

// (R95: PreSrResetPipeline/EnsureObjects/StageGain/RecordCompose and
//  the whole deferred-compose block were removed with the pre-SR mode.
//  SealColorPost below is the only colour seal left.)

void SealColorPost(const EvalArgs& a)
{
    Session& s = g_s;
    if (g_st.load(std::memory_order_acquire) != (int) St::Live) return;
    if (a.inCmdList == nullptr || a.dstOutput == nullptr) return;
    if (s.inColor.buf == nullptr) return;

    ID3D12Resource* src = a.dstOutput;
    const D3D12_RESOURCE_DESC sd = src->GetDesc();
    D3D12_RESOURCE_BARRIER bar {};
    bar.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
    bar.Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
    bar.Transition.pResource = src;
    bar.Transition.StateBefore = D3D12_RESOURCE_STATE_UNORDERED_ACCESS;
    bar.Transition.StateAfter = D3D12_RESOURCE_STATE_COPY_SOURCE;
    a.inCmdList->ResourceBarrier(1, &bar);
    D3D12_TEXTURE_COPY_LOCATION srcL { src,
        D3D12_TEXTURE_COPY_TYPE_SUBRESOURCE_INDEX };
    D3D12_TEXTURE_COPY_LOCATION dst { s.inColor.buf.Get(),
        D3D12_TEXTURE_COPY_TYPE_PLACED_FOOTPRINT };
    dst.PlacedFootprint.Footprint.Format =
        (DXGI_FORMAT) FootprintFmt((unsigned) sd.Format);
    dst.PlacedFootprint.Footprint.Width = s.inW;
    dst.PlacedFootprint.Footprint.Height = s.inH;
    dst.PlacedFootprint.Footprint.Depth = 1;
    dst.PlacedFootprint.Footprint.RowPitch =
        PitchFor(s.inW, BppFor((unsigned) sd.Format));
    D3D12_BOX box {};
    box.left = 0; box.top = 0; box.front = 0;
    box.right = s.inW; box.bottom = s.inH; box.back = 1;
    a.inCmdList->CopyTextureRegion(&dst, 0, 0, 0, &srcL, &box);
    bar.Transition.StateBefore = D3D12_RESOURCE_STATE_COPY_SOURCE;
    bar.Transition.StateAfter = D3D12_RESOURCE_STATE_UNORDERED_ACCESS;
    a.inCmdList->ResourceBarrier(1, &bar);
}

