// windows.h defines min/max as macros — a plain helper avoids the clash.
template <typename T> T MinOf(T a, T b) { return a < b ? a : b; }

void EnqueueReconfig(Reason r)
{
    // R88.4 (R85w port): reconfigs are rare and decisive — always on the
    // record. LogRate shares ONE throttle slot across every call-site (the
    // table keys on the format-string pointer): repeated enqueues
    // (LateGuides/Drs at frame rate) swallowed the line of the request
    // that mattered (the 13:02 wedge had NO reconfig trace at all).
    Log("session: reconfig requested (%s)", ReasonName(r));
    {
        std::lock_guard<std::mutex> lk(g_reconfigCs);
        g_reconfigPending = true;
        g_reconfigReason = r;  // latest wins (coalescing table, fsm-design)
    }
    if (g_poke != nullptr)
        SetEvent(g_poke);
}

