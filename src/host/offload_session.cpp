void Configure(int adapterIndex)
{
    std::lock_guard<std::mutex> lk(g_s.cs);
    if (adapterIndex < 0)
        return;  // pass-through only; nothing to tear down yet
    g_s.enabled = true;
    // Tuning must hold its defaults + user config BEFORE the ctl server
    // starts mirroring it (and before any arm relays it into the mapping).
    if (!g_s.tuningInit)
    {
        TuningDefaults();
        CtlLoadIni();  // once per process; live changes layer on top
        g_s.tuningInit = true;
    }
    Log("session: offload enabled (delta compose, out of process)");
    // The panel/CLI link lives from NGX init (the menu), not from the first
    // evaluate — tuning is reachable before gameplay starts (R64c).
    CtlStart();
    if (g_poke == nullptr)
        g_poke = CreateEventW(nullptr, FALSE, FALSE, nullptr);
    if (g_thread == nullptr)
        g_thread = CreateThread(nullptr, 0, SessionThread, nullptr, 0, nullptr);
}

// Evaluate/PresentGate run on the GAME thread, inside the game's own
// D3D12 calls. A C++ exception escaping here kills the whole game (R75 live
// forensics: E06D7363 -> WER -> dead game 26 ms after READY). Neither entry
// point may ever throw past us: catch everything, log what(), and degrade to
// a re-arm (the frame goes native — the offload never blocks the game).
static void EvaluateInner(const EvalArgs& a);

void Evaluate(const EvalArgs& a)
{
    try
    {
        EvaluateInner(a);
    }
    catch (const std::exception& e)
    {
        LogRate(1000, "session: EVALUATE exception (%s) - re-arm", e.what());
        EnqueueReconfig(Reason::FailStreak);
    }
    catch (...)
    {
        LogRate(1000, "session: EVALUATE exception (non-std) - re-arm");
        EnqueueReconfig(Reason::FailStreak);
    }
}

static void EvaluateInner(const EvalArgs& a)
{
    const int st = g_st.load(std::memory_order_acquire);
    if (st != (int) St::Live)
    {
        // IDLE + a fresh evaluate is the arm trigger: publish a snapshot
        // (POD + device reference) and poke the session thread. The game
        // thread never arms and never waits.
        if (st == (int) St::Idle && g_s.enabled && !g_s.failedPermanent &&
            !g_shutdown && a.gameDev != nullptr && a.srcColor != nullptr &&
            a.dstOutput != nullptr && a.inW && a.inH)
        {
            Session::Arm arm;
            arm.valid = true;
            arm.dev = a.gameDev;
            arm.inW = a.inW; arm.inH = a.inH;
            arm.outW = a.outW; arm.outH = a.outH;
            arm.colorFmt = a.srcColor->GetDesc().Format;
            arm.outFmt = a.dstOutput->GetDesc().Format;
            arm.hasDepth = a.srcDepth != nullptr;
            arm.hasMv = a.srcMotion != nullptr;
            if (a.srcDepth != nullptr)
                arm.depthDesc = a.srcDepth->GetDesc();
            arm.mvFmt = a.srcMotion != nullptr
                ? a.srcMotion->GetDesc().Format : DXGI_FORMAT_UNKNOWN;
            arm.srFlags = a.createFlags;
            {
                std::lock_guard<std::mutex> lk(g_s.armCs);
                g_s.arm = arm;  // overwrite: freshest frame wins
            }
            if (g_poke != nullptr)
                SetEvent(g_poke);
        }
        return;
    }

    FrameGuard guard;
    // re-check inside the guard: a drain may have started between the load
    // and the guard
    if (g_st.load(std::memory_order_acquire) != (int) St::Live)
        return;
    Session& s = g_s;

    // offload A/B: forward this frame to native, nothing else. The pending
    // triple goes stale too — the engine will produce nothing for it.
    if (s.tuning.offloadOn == 0)
    {
        std::lock_guard<std::mutex> lk(s.pendingCs);
        s.pendingValid = false;
        s.pendingList = nullptr;
        return;
    }

    // geometry guard: everything was sized at arm time; a different
    // geometry needs a full re-arm (the engine guards on its side too).
    // R82h/R95: the colour transported is ALWAYS the frame's SR output
    // (display res) — POST-SR is the only placement.
    const unsigned wantW = a.outW;
    const unsigned wantH = a.outH;
    if (wantW != s.inW || wantH != s.inH)
    {
        // R88 diagnostic: the Drs reconfig is the one early-return that can
        // freeze produce with NO visible log (EnqueueReconfig throttles) —
        // name the geometry 1/5s until the drain line shows up.
        LogRate(5000, "session: evaluate geometry moved %ux%u -> %ux%u "
                "(reconfig queued)", s.inW, s.inH, wantW, wantH);
        EnqueueReconfig(Reason::Drs);
        return;
    }

    // remember the queue the frame's list will run on: DRAINING flushes it
    // before releasing anything the recorded lists reference.
    // (R95 audit: the ComPtr is shared with the session thread — the drain
    //  resets it at 2220 while the game thread may be reading it here or
    //  in ComposeStageDraw. ALL touches now take pendingCs and copy the
    //  raw pointer out; the ComPtr keeps the reference alive.)
    if (a.gameQueue != nullptr)
    {
        std::lock_guard<std::mutex> lk(s.pendingCs);
        s.gameQueueForFlush = a.gameQueue;
    }

    // ---- engine health poll (delivery itself moved to Present, R79) ----
    if (s.scalars != nullptr)
        memcpy((uint8_t*) s.scalars + TUNING_OFFSET, &s.tuning,
               sizeof(s.tuning));
    if (s.pendingValid && s.doneFence != nullptr)
    {
        const UINT64 done = s.doneFence->GetCompletedValue();
        if (done == UINT64_MAX)
        {
            // engine-side TDR or poison: the session thread re-arms (the
            // game device check happens there)
            EnqueueReconfig(Reason::FencePoison);
            return;
        }
        // R89a (A3): re-check Live IMMEDIATELY before touching engine-owned
        // handles — DoDrain closes pi.hProcess on the session thread and
        // only then waits for the FrameGuard, so a stale game-thread pass
        // could wait on a closed handle (UB). The drain path guarantees
        // st != Live across the whole handle teardown; if Live still holds
        // here, the handles are guaranteed alive (DoArm repopulates them
        // only under g_s.cs, and st goes Draining->...->Live only after).
        if (g_st.load(std::memory_order_acquire) != (int) St::Live)
            return;
        if (WaitForSingleObject(s.pi.hProcess, 0) == WAIT_OBJECT_0)
        {
            EnqueueReconfig(Reason::EngineDead);
            return;
        }
        if (done > s.lastDeliveredDone)
        {
            s.lastDeliveredDone = done;
            if (s.scalars->engineResult == 0)
            {
                // exception path in the engine: it still delivers (a zero
                // delta), but a 90 s streak means the session is wedged
                ++s.consecutiveFailures;
                if (s.consecutiveFailures == 1)
                    s.firstFailureTick = GetTickCount64();
                if (s.consecutiveFailures % 120 == 0)
                    LogRate(5000, "session: engine failing (%u consecutive)",
                            s.consecutiveFailures);
                if (GetTickCount64() - s.firstFailureTick > 90000)
                {
                    EnqueueReconfig(Reason::FailStreak);
                    return;
                }
            }
            else
                s.consecutiveFailures = 0;
        }
    }

    // ---- scalars for the frame being sealed ---------------------------
    ++s.frame;
    s.scalars->frame = s.frame;
    s.scalars->mvScaleX = a.mvScaleX;
    s.scalars->mvScaleY = a.mvScaleY;
    s.scalars->reset = a.gameReset ? 1u : 0u;
    s.scalars->engineResult = 0;
    // the engine compares these against the transport dims (DRS guard R60):
    // report the colour actually being sent (post-SR = display res).
    s.scalars->renderW = s.inW;
    s.scalars->renderH = s.inH;
    // (R95: jitter scalars are always 0 — the transported colour is the
    //  game's de-jittered SR output; the model never sees raw jitter.)
    s.scalars->jitterX = 0.f;
    s.scalars->jitterY = 0.f;
    s.scalars->preExposure = a.preExposure;

    if (a.inCmdList == nullptr)
        return;  // nothing to record into: native frame

    if (!RecordSealFrame(a, a.inCmdList))
        return;

    {
        std::lock_guard<std::mutex> lk(s.pendingCs);
        s.pendingValid = true;
        s.pendingFrame = s.frame;
        s.pendingList = a.inCmdList;
    }
    // The caller ALWAYS continues into the native evaluate: composition
    // happens later, at the game's Present call (PresentGate below).
}

